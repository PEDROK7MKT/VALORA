// Idioma inicial: ?lang= → escolha guardada (vale para o site principal também) →
// idiomas do aparelho → francês.
export function detectLang(storage) {
  try {
    const q = new URLSearchParams(window.location.search).get('lang');
    if (q && LANGS.includes(q)) { storage.set(STORAGE_KEY, q); return q; }
  } catch (e) { /* sem query */ }
  const saved = storage.get(STORAGE_KEY);
  if (saved && LANGS.includes(saved)) return saved;
  const prefs = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || ''];
  for (const p of prefs) {
    const c = String(p).slice(0, 2).toLowerCase();
    if (LANGS.includes(c)) return c;
  }
  return 'fr';
}
